// Helper function to get country calling code
export const getCountryCallingCode = (countryCode: string): number => {
	try {
		return phoneUtil.getCountryCodeForRegion(countryCode)
	} catch {
		return 0
	}
}

// Helper function to parse phone number
export const parsePhoneNumber = (
	phoneNumberString: string,
	defaultCountry?: string
) => {
	try {
		const parsed = phoneUtil.parse(phoneNumberString, defaultCountry)

		if (!parsed) return { number: phoneNumberString, country: defaultCountry }

		return {
			country: phoneUtil.getRegionCodeForNumber(parsed),
			nationalNumber: parsed.getNationalNumber()?.toString() || '',
			number: phoneUtil.format(parsed, PhoneNumberFormat.E164),
		}
	} catch {
		return { number: phoneNumberString, country: defaultCountry }
	}
}

// Helper function to validate phone number
export const isValidPhoneNumber = (
	phoneNumberString: string,
	defaultCountry?: string
): boolean => {
	try {
		const parsed = phoneUtil.parse(phoneNumberString, defaultCountry)
		return phoneUtil.isValidNumber(parsed)
	} catch {
		return false
	}
}

export const getPhoneNumberLengthRange = (countryCode: string) => {
	const exampleNumber = phoneUtil.getExampleNumber(countryCode)

	if (!exampleNumber) return null

	const nationalNumber = exampleNumber?.getNationalNumber()?.toString() || ''

	return {
		length: nationalNumber.length,
		number: nationalNumber,
	}
}

